#!/usr/bin/env python3
"""Generates the fixed 6x7 month-grid layouts and MonthIds.kt.

RemoteViews can't reliably re-apply dynamically added cells, so the grid is static XML with
predefined ids: box<i> (cell container, gets the "today" fill), c<i> (day number), d<i> (event dot).
Run from the repo root: python3 tools/gen_month_layouts.py
"""
from pathlib import Path

RES = Path("app/src/main/res/layout")
KT = Path("app/src/main/java/com/paulli/icalwidget/MonthIds.kt")

HEADER_BUTTONS = '''
        <ImageView
            android:id="@+id/prev_button"
            android:layout_width="36dp"
            android:layout_height="36dp"
            android:contentDescription="@string/prev_month"
            android:padding="6dp"
            android:src="@drawable/ic_chevron_left" />

        <ImageView
            android:id="@+id/next_button"
            android:layout_width="36dp"
            android:layout_height="36dp"
            android:layout_marginEnd="4dp"
            android:contentDescription="@string/next_month"
            android:padding="6dp"
            android:src="@drawable/ic_chevron_right" />

        <ImageView
            android:id="@+id/refresh_button"
            android:layout_width="36dp"
            android:layout_height="36dp"
            android:background="@drawable/refresh_bg"
            android:contentDescription="@string/refresh"
            android:padding="8dp"
            android:src="@drawable/ic_refresh" />'''


def cell(i, dots, text_size):
    # The dot is overlaid at the bottom of the cell rather than stacked under the number, so short
    # rows (a small widget) can't clip it.
    dot = (f'''
                <ImageView android:id="@+id/d{i}" android:layout_width="5dp" android:layout_height="5dp" android:layout_gravity="bottom|center_horizontal" android:layout_marginBottom="2dp" android:importantForAccessibility="no" android:src="@drawable/event_dot" android:visibility="invisible" />'''
           if dots else "")
    pad = ' android:paddingBottom="4dp"' if dots else ""
    return f'''            <FrameLayout android:id="@+id/box{i}" android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="1" android:layout_margin="1.5dp">
                <TextView android:id="@+id/c{i}" android:layout_width="match_parent" android:layout_height="match_parent" android:gravity="center"{pad} android:textColor="@color/widget_text" android:textSize="{text_size}" />{dot}
            </FrameLayout>'''


def panel(dots, buttons, text_size, title_size):
    rows = []
    for w in range(6):
        cells = "\n".join(cell(w * 7 + d, dots, text_size) for d in range(7))
        rows.append(f'''        <LinearLayout android:id="@+id/week{w}" android:layout_width="match_parent" android:layout_height="0dp" android:layout_weight="1" android:orientation="horizontal">
{cells}
        </LinearLayout>''')
    weekdays = "\n".join(
        f'''        <TextView android:id="@+id/wd{i}" android:layout_width="0dp" android:layout_height="wrap_content" android:layout_weight="1" android:gravity="center" android:textColor="@color/widget_text_secondary" android:textSize="11sp" android:textStyle="bold" />'''
        for i in range(7))
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_month_layouts.py; edit the script, not this file. -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:orientation="vertical">

    <LinearLayout
        android:layout_width="match_parent"
        android:layout_height="wrap_content"
        android:minHeight="36dp"
        android:gravity="center_vertical"
        android:orientation="horizontal">

        <TextView
            android:id="@+id/month_title"
            android:layout_width="0dp"
            android:layout_height="wrap_content"
            android:layout_weight="1"
            android:paddingStart="4dp"
            android:singleLine="true"
            android:ellipsize="end"
            android:textColor="@color/widget_accent"
            android:textSize="{title_size}"
            android:textStyle="bold" />{HEADER_BUTTONS if buttons else ""}
    </LinearLayout>

    <LinearLayout
        android:layout_width="match_parent"
        android:layout_height="wrap_content"
        android:layout_marginTop="6dp"
        android:layout_marginBottom="2dp"
        android:orientation="horizontal">
{weekdays}
    </LinearLayout>

    <LinearLayout
        android:layout_width="match_parent"
        android:layout_height="0dp"
        android:layout_weight="1"
        android:orientation="vertical">
{chr(10).join(rows)}
    </LinearLayout>
</LinearLayout>
'''


(RES / "month_panel.xml").write_text(panel(dots=True, buttons=True, text_size="13sp", title_size="18sp"))
(RES / "month_panel_simple.xml").write_text(panel(dots=True, buttons=False, text_size="15sp", title_size="18sp"))

ids = lambda p, n: ", ".join(f"R.id.{p}{i}" for i in range(n))
KT.write_text(f'''package com.paulli.icalwidget

// Generated by tools/gen_month_layouts.py.
object MonthIds {{
    val weekdays = intArrayOf({ids("wd", 7)})
    val weeks = intArrayOf({ids("week", 6)})
    val boxes = intArrayOf({ids("box", 42)})
    val days = intArrayOf({ids("c", 42)})
    val dots = intArrayOf({ids("d", 42)})
}}
''')
print("ok")
